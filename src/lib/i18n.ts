export type Language = "zh-CN" | "zh-TW" | "en" | "ja" | "ko";

export const DEFAULT_LANGUAGE: Language = "zh-CN";

export const LANGUAGE_OPTIONS: ReadonlyArray<{
  value: Language;
  label: string;
  shortLabel: string;
  htmlLang: string;
}> = [
  { value: "zh-CN", label: "简体中文", shortLabel: "简中", htmlLang: "zh-CN" },
  { value: "zh-TW", label: "繁體中文", shortLabel: "繁中", htmlLang: "zh-Hant" },
  { value: "en", label: "English", shortLabel: "EN", htmlLang: "en" },
  { value: "ja", label: "日本語", shortLabel: "日本語", htmlLang: "ja" },
  { value: "ko", label: "한국어", shortLabel: "한국어", htmlLang: "ko" },
];

export function isLanguage(value: unknown): value is Language {
  return LANGUAGE_OPTIONS.some((item) => item.value === value);
}

export function detectLanguage(languages: readonly string[] = []): Language {
  for (const raw of languages) {
    const lang = raw.toLowerCase();
    if (lang === "zh-tw" || lang === "zh-hk" || lang === "zh-mo" || lang.includes("hant")) {
      return "zh-TW";
    }
    if (lang === "zh-cn" || lang === "zh-sg" || lang.includes("hans")) {
      return "zh-CN";
    }
    if (lang === "ja" || lang.startsWith("ja-")) return "ja";
    if (lang === "ko" || lang.startsWith("ko-")) return "ko";
    if (lang === "en" || lang.startsWith("en-")) return "en";
    if (lang === "zh" || lang.startsWith("zh-")) return "zh-CN";
  }
  return DEFAULT_LANGUAGE;
}

